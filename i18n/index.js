const LANGUAGE_KEY = 'siamfeast_language'

// 用 Vue.observable 包装 state，让 i18n.t() 自动响应式
// 任何调用 i18n.t() 的 computed/methods/模板表达式都会跟随 state.language 变化重新求值
let _state = {
	language: 'th',  // 默认泰语（用户没选过语言时）
	messages: messages
}
// uni-app 环境：vue 全局可用（不需要 import）
// #ifndef VUE3
try {
	if (typeof Vue !== 'undefined' && Vue && typeof Vue.observable === 'function') {
		_state = Vue.observable(_state)
	}
} catch (e) {
	console.warn('[i18n] Vue.observable failed:', e)
}
// #endif
// #ifdef VUE3
// Vue 3 reactive：从 vue 包导入（uni-app vue3 编译期会注入）
try {
	const { reactive } = require('vue')
	if (typeof reactive === 'function') {
		_state = reactive(_state)
	}
} catch (e) {}
// #endif

const i18n = {
	state: _state,

	/**
	 * 初始化语言
	 * - 用户之前选过语言 → 用存储的语言
	 * - 没选过 → 默认泰语
	 */
	init() {
		try {
			const savedLang = uni.getStorageSync(LANGUAGE_KEY)
			if (savedLang && messages[savedLang]) {
				this.state.language = savedLang
			} else {
				this.state.language = 'th'
				uni.setStorageSync(LANGUAGE_KEY, 'th')
			}
		} catch (e) {
			console.error('i18n init error:', e)
		}
	},

	/**
	 * 获取当前语言
	 * @returns {string}
	 */
	getLanguage() {
		return this.state.language
	},

	/**
	 * 设置语言
	 * @param {string} lang - zh | en | th
	 */
	setLanguage(lang) {
		if (messages[lang]) {
			this.state.language = lang
			try {
				uni.setStorageSync(LANGUAGE_KEY, lang)
			} catch (e) {
				console.error('setLanguage error:', e)
			}
				uni.$emit("languageChanged")
		}
	},

	/**
	 * 获取翻译文本
	 * @param {string} key - 点分隔的键名，如 'index.dineIn'
	 * @param {object} params - 替换参数，如 { count: 5 }
	 * @returns {string}
	 */
	t(key, params = {}) {
		const keys = key.split('.')
		let value = messages[this.state.language]

		for (const k of keys) {
			if (value && typeof value === 'object') {
				value = value[k]
			} else {
				return key
			}
		}

		if (typeof value !== 'string') {
			return key
		}

		// 替换参数
		let result = value
		Object.keys(params).forEach(paramKey => {
			result = result.replace(new RegExp(`\\{${paramKey}\\}`, 'g'), params[paramKey])
		})

		return result
	},

	/**
	 * 获取所有语言列表
	 * @returns {Array}
	 */
	getLanguages() {
		return [
			{ code: 'zh', name: '中文', nativeName: '中文' },
			{ code: 'en', name: 'English', nativeName: 'English' },
			{ code: 'th', name: 'Thai', nativeName: 'ภาษาไทย' }
		]
	}
}

// 初始化
i18n.init()

export default i18n
